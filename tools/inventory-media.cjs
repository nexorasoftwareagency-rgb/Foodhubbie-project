#!/usr/bin/env node
/**
 * Batch 15 inventory: which `data:image` fields are still in RTDB, of what kind,
 * and where. Read-only. Run from the repo root:
 *   node tools/inventory-media.cjs
 */
'use strict';
const path = require('path');
const ROOT = path.resolve(__dirname, '..');
const admin = require(path.join(ROOT, 'bot/node_modules/firebase-admin'));
const sa = require(path.join(ROOT, 'bot/service-account.json'));

const DB = 'https://foodhubbie-10-default-rtdb.firebaseio.com';
const app = admin.initializeApp({
  credential: admin.credential.cert(sa),
  databaseURL: DB,
});
const db = app.database();

function walk(node, prefix, out) {
  if (typeof node === 'string') {
    if (node.startsWith('data:image/')) out.push({ path: prefix, value: node });
    return;
  }
  if (!node || typeof node !== 'object') return;
  for (const [k, v] of Object.entries(node)) walk(v, prefix ? `${prefix}/${k}` : k, out);
}

function kindOf(v) {
  if (v.startsWith('data:image/svg+xml')) return 'svg-text';
  if (/^data:image\/[a-z0-9.+-]+;base64,/i.test(v)) return 'base64';
  return 'other-uri';
}

(async () => {
  const businesses = (await db.ref('businesses').get()).val() || {};
  const rows = [];

  for (const [bid, biz] of Object.entries(businesses)) {
    for (const [oid, outlet] of Object.entries((biz && biz.outlets) || {})) {
      const hits = [];
      walk(outlet, '', hits);
      for (const h of hits) {
        rows.push({
          scope: 'outlet',
          tenant: `${bid}/${oid}`,
          branch: h.path.split('/')[0],
          path: `${bid}/${oid}/${h.path}`,
          kind: kindOf(h.value),
          bytes: Buffer.byteLength(h.value, 'utf8'),
        });
      }
    }
  }

  const bank = (await db.ref('menuBank').get()).val() || {};
  const bankHits = [];
  walk(bank, '', bankHits);
  for (const h of bankHits) {
    rows.push({
      scope: 'menuBank',
      tenant: '(platform)',
      branch: h.path.split('/')[0],
      path: `menuBank/${h.path}`,
      kind: kindOf(h.value),
      bytes: Buffer.byteLength(h.value, 'utf8'),
    });
  }

  const fmt = (n) => (n / 1024).toFixed(1) + ' KB';
  const total = rows.reduce((a, r) => a + r.bytes, 0);

  console.log(`data:image fields in RTDB: ${rows.length}  (${(total / 1048576).toFixed(2)} MB of JSON string)\n`);

  console.log('=== by kind ===');
  for (const kind of ['base64', 'svg-text', 'other-uri']) {
    const rs = rows.filter((r) => r.kind === kind);
    if (!rs.length) continue;
    console.log(`  ${kind.padEnd(10)} ${String(rs.length).padStart(3)} field(s)  ${fmt(rs.reduce((a, r) => a + r.bytes, 0))}`);
  }

  console.log('\n=== base64 only, by tenant ===');
  const byTenant = {};
  for (const r of rows.filter((x) => x.kind === 'base64')) {
    byTenant[r.path.split('/').slice(0, r.scope === 'menuBank' ? 1 : 2).join('/')] = byTenant[r.path.split('/').slice(0, r.scope === 'menuBank' ? 1 : 2).join('/')] || { n: 0, b: 0, branches: {} };
    const key = r.path.split('/').slice(0, r.scope === 'menuBank' ? 1 : 2).join('/');
    byTenant[key].n++;
    byTenant[key].b += r.bytes;
    byTenant[key].branches[r.branch] = (byTenant[key].branches[r.branch] || 0) + 1;
  }
  for (const [k, v] of Object.entries(byTenant).sort((a, b) => b[1].b - a[1].b)) {
    console.log(`  ${k.padEnd(52)} ${String(v.n).padStart(3)}  ${fmt(v.b).padStart(9)}  ${JSON.stringify(v.branches)}`);
  }

  console.log('\n=== svg-text (NOT migratable as images — text, tiny, regenerated by the demo seeder) ===');
  const svgByTenant = {};
  for (const r of rows.filter((x) => x.kind === 'svg-text')) {
    const key = r.path.split('/').slice(0, r.scope === 'menuBank' ? 1 : 2).join('/');
    svgByTenant[key] = svgByTenant[key] || { n: 0, b: 0 };
    svgByTenant[key].n++;
    svgByTenant[key].b += r.bytes;
  }
  for (const [k, v] of Object.entries(svgByTenant).sort((a, b) => b[1].b - a[1].b)) {
    console.log(`  ${k.padEnd(52)} ${String(v.n).padStart(3)}  ${fmt(v.b).padStart(9)}`);
  }

  console.log('\n=== every base64 field (tenant/branch/path -> bytes) ===');
  for (const r of rows.filter((x) => x.kind === 'base64').sort((a, b) => b.bytes - a.bytes)) {
    console.log(`  ${r.path.slice(0, 78).padEnd(80)} ${String(r.bytes).padStart(8)} B`);
  }

  process.exit(0);
})().catch((e) => { console.error('ERR', e.code || '', e.message); process.exit(1); });
